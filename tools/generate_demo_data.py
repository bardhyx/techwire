def build(defs, default_cat, start_id, minute_offsets):
    out = []
    for i, d in enumerate(defs):
        cat = d.get("category", default_cat)
        aid = start_id + i
        author = DESK_AUTHOR.get(cat, "newsroom")
        if d["type"] == "News" and cat == "Cybersecurity" and d.get("isBreaking"):
            author = "security-desk"
        pub = ANCHOR - dt.timedelta(minutes=minute_offsets[i])
        upd = pub + dt.timedelta(minutes=[0, 12, 25, 40, 5][aid % 5])
        words = 520 + (aid * 37) % 900
        art = {
            "id": aid,
            "slug": slug(d["title"]),
            "title": d["title"],
            "category": cat,
            "subcategory": d["subcategory"],
            "type": d["type"],
            "author": author,
            "date": pub.isoformat(),
            "updated": upd.isoformat() if upd > pub else None,
            "readingTime": max(3, round(words / 200)),
            "summary": d["summary"],
            "image": None,
            "imageAlt": f"Editorial illustration for {cat.lower()} story: {d['subcategory']}",
            "tags": d["tags"],
            "isBreaking": d.get("isBreaking", False),
            "featured": d.get("featured", False),
            "isDemo": True,
            "cve": d.get("cve"),
            "cvss": d.get("cvss"),
            "severity": d.get("severity"),
            "views": 1200 + (aid * 7919) % 48000,
            "trendingScore": round(((aid * 37) % 100) / 10 + (8 if d.get("isBreaking") else 0) + (3 if d.get("cve") else 0), 1),
            "brief": {"what": d["summary"], "who": d["who"], "why": SUB[d["subcategory"]][2], "next": d["next"]},
            "whyItMatters": SUB[d["subcategory"]][2] + " " + SUB[d["subcategory"]][3],
            "sections": body_for(d),
            "sources": sources_for(d),
        }
        if cat in ("Cybersecurity", "Networking", "Infrastructure", "Cloud", "Hardware") or d.get("cve") or d["subcategory"] in ("AI Security", "AI Vulnerabilities"):
            art["forProfessionals"] = {
                "systems": d["who"],
                "network": "Review exposure of affected services and management interfaces at network boundaries." if cat != "Networking" else SUB[d["subcategory"]][1],
                "security": SUB[d["subcategory"]][1] if cat != "Networking" else "Validate control-plane protections, filtering and monitoring on affected devices.",
                "checks": SUB[d["subcategory"]][3],
                "detection": "Correlate device, authentication and network logs for activity outside expected maintenance windows." if not d.get("cve") else f"Search logs for requests to the affected component and review vendor indicators referenced for {d['cve']}.",
                "advisory": "Vendor advisory (demo placeholder - link to the official advisory when available)",
            }
        out.append(art)
    return out

def offsets(n, start, step):
    return [start + i * step + (i * 7) % 11 for i in range(n)]

